#!/usr/bin/env bun
/**
 * Generates the mobile translation catalog from `locales/*.yml`.
 *
 * The web client reads those YAML files directly through Vite's `?raw` import.
 * Metro has no equivalent, and a runtime YAML parser in the app bundle would
 * add weight and a second parser to keep in sync with the Rust one. Instead
 * this writes a plain ES module the app imports like any other source file.
 *
 * `--check` verifies the checked-in output matches the YAML and exits non-zero
 * otherwise, so CI catches a locale edit that skipped regeneration.
 */
import { mkdir } from 'node:fs/promises'
import { dirname, join } from 'node:path'

import { parseRustI18nCatalog } from '../packages/waku-i18n/src/i18n-core.ts'

const ROOT = join(import.meta.dir, '..')
const OUTPUT = join(ROOT, 'apps/mobile/src/lib/i18n-catalog.ts')

// Mirrors LOCALE_FILES in packages/waku-i18n/src/i18n-core.test.ts and the
// `_LOCALE_SOURCES` list in src/lib.rs.
const LOCALES = [
  ['en', 'app.yml'],
  ['zh-CN', 'zh-CN.yml'],
  ['ja', 'ja.yml'],
] as const

type Locale = (typeof LOCALES)[number][0]

async function build() {
  const catalogs: Record<string, Record<string, string>> = {}
  for (const [locale, file] of LOCALES) {
    const source = await Bun.file(join(ROOT, 'locales', file)).text()
    catalogs[locale] = parseRustI18nCatalog(source, locale as Locale)
  }

  const english = catalogs.en!
  const keys = Object.keys(english).sort()
  const missing = LOCALES
    .filter(([locale]) => locale !== 'en')
    .flatMap(([locale]) => keys
      .filter((key) => !(key in catalogs[locale]!))
      .map((key) => `${locale}: ${key}`))
  if (missing.length) {
    throw new Error(`locale catalogs are out of sync:\n${missing.join('\n')}`)
  }

  // One flat key/value map per locale, keyed by the English set so every
  // catalog has identical shape. Rows are sorted for a stable diff.
  const rows = LOCALES.map(([locale]) => {
    const entries = keys
      .map((key) => `    ${JSON.stringify(key)}: ${JSON.stringify(catalogs[locale]![key]!)}`)
      .join(',\n')
    return `  ${JSON.stringify(locale)}: {\n${entries}\n  }`
  }).join(',\n')

  return `// Generated by scripts/generate-i18n-catalog.ts from locales/*.yml.
// Do not edit by hand: run \`bun run i18n:generate\` after changing a locale.
import type { AppLocale } from '@waku/i18n'

export const MOBILE_CATALOG: Record<AppLocale, Record<string, string>> = {
${rows}
}
`
}

const output = await build()

if (process.argv.includes('--check')) {
  const existing = await Bun.file(OUTPUT).text().catch(() => null)
  if (existing !== output) {
    console.error(
      `${OUTPUT} is out of date with locales/*.yml.\nRun \`bun run i18n:generate\` and commit the result.`,
    )
    process.exit(1)
  }
  console.log('i18n catalog is up to date')
} else {
  await mkdir(dirname(OUTPUT), { recursive: true })
  await Bun.write(OUTPUT, output)
  console.log(`Wrote ${OUTPUT}`)
}
